-- Step 027: a versioned, trainable prompt for the AI coach, and the training
-- workspace that improves it.
--
-- The coach's judgment used to be a constant in api/coach.ts. It now lives in
-- coach_prompt_versions, an append-only history (seed, AI revision from
-- feedback, direct instruction, hand edit, restore), and coach_prompt_state
-- says which version the training page is working on and which one every
-- coach uses. The fixed harness (message tags, output contract, the rule that
-- sequence messages are never critiqued) stays in code.
--
-- The training workspace references live conversations, never copies them:
--
-- * coach_training_cases: one active case per conversation, with an optional
--   cut point (coach "as of" that message).
-- * coach_training_runs: one coach output per run, append-only, with the
--   marker of the thread it read, so a run whose thread has changed since is
--   labelled as such.
-- * coach_training_feedback: a verdict and/or comment on a run's take, one of
--   its ideas or one of its issues. An improve round marks the feedback it used
--   (consumed_by_version_id); clearing feedback sets both fields NULL.
--
-- conversation_coaching gains prompt_version_id: which version produced a
-- cached take (NULL = the built-in prompt), so a publish can be shown as stale.
--
-- Scope is 'global' only. The column exists so a per-account variant
-- ('instance:<id>') can be added later without rewriting these rows.
--
-- Every active team member may train and publish (owner decision 2026-10-20).
-- RLS: active members through app_runtime / app_readonly, like the sequence
-- workspace (step 011). No DELETE is granted to anyone; a case is archived,
-- a version is never removed. No AI sandbox access. The seed version is not
-- written here: the app creates it from its built-in prompt on first use, so
-- the prompt text has a single home.

SET ROLE app_owner;

CREATE TABLE public.coach_prompt_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    scope text DEFAULT 'global' NOT NULL,
    n integer NOT NULL,
    prompt text NOT NULL,
    source text NOT NULL,
    parent_id bigint,
    changelog jsonb DEFAULT '[]'::jsonb NOT NULL,
    unaddressed jsonb DEFAULT '[]'::jsonb NOT NULL,
    note text,
    created_by uuid NOT NULL,
    created_by_name text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT coach_prompt_versions_pkey PRIMARY KEY (id),
    CONSTRAINT coach_prompt_versions_scope_n_key UNIQUE (scope, n),
    CONSTRAINT coach_prompt_versions_parent_fkey FOREIGN KEY (parent_id)
        REFERENCES public.coach_prompt_versions(id),
    CONSTRAINT coach_prompt_versions_created_by_fkey FOREIGN KEY (created_by)
        REFERENCES public.users(id),
    CONSTRAINT coach_prompt_versions_scope_check CHECK (scope ~ '^(global|instance:.{1,200})$'),
    CONSTRAINT coach_prompt_versions_n_check CHECK (n > 0),
    CONSTRAINT coach_prompt_versions_prompt_check
        CHECK (char_length(btrim(prompt)) >= 1 AND char_length(prompt) <= 40000),
    CONSTRAINT coach_prompt_versions_source_check
        CHECK (source IN ('seed', 'feedback', 'instruction', 'manual', 'revert')),
    CONSTRAINT coach_prompt_versions_changelog_check CHECK (jsonb_typeof(changelog) = 'array'),
    CONSTRAINT coach_prompt_versions_unaddressed_check CHECK (jsonb_typeof(unaddressed) = 'array'),
    CONSTRAINT coach_prompt_versions_note_check CHECK (note IS NULL OR char_length(note) <= 8000),
    CONSTRAINT coach_prompt_versions_created_by_name_check
        CHECK (char_length(btrim(created_by_name)) BETWEEN 1 AND 120)
);

CREATE TABLE public.coach_prompt_state (
    scope text NOT NULL,
    working_version_id bigint NOT NULL,
    published_version_id bigint,
    revision bigint DEFAULT 1 NOT NULL,
    published_at timestamp with time zone,
    published_by uuid,
    published_by_name text,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT coach_prompt_state_pkey PRIMARY KEY (scope),
    CONSTRAINT coach_prompt_state_working_fkey FOREIGN KEY (working_version_id)
        REFERENCES public.coach_prompt_versions(id),
    CONSTRAINT coach_prompt_state_published_fkey FOREIGN KEY (published_version_id)
        REFERENCES public.coach_prompt_versions(id),
    CONSTRAINT coach_prompt_state_published_by_fkey FOREIGN KEY (published_by)
        REFERENCES public.users(id),
    CONSTRAINT coach_prompt_state_scope_check CHECK (scope ~ '^(global|instance:.{1,200})$'),
    CONSTRAINT coach_prompt_state_revision_check CHECK (revision > 0)
);

CREATE TABLE public.coach_training_cases (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    instance_id text NOT NULL,
    profile_url text NOT NULL,
    campaign_id text,
    cut_after_message_id bigint,
    note text,
    archived_at timestamp with time zone,
    created_by uuid NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT coach_training_cases_pkey PRIMARY KEY (id),
    CONSTRAINT coach_training_cases_instance_fkey FOREIGN KEY (instance_id)
        REFERENCES public.instances(id) ON DELETE CASCADE,
    CONSTRAINT coach_training_cases_cut_fkey FOREIGN KEY (cut_after_message_id)
        REFERENCES public.messages(id) ON DELETE SET NULL,
    CONSTRAINT coach_training_cases_created_by_fkey FOREIGN KEY (created_by)
        REFERENCES public.users(id),
    CONSTRAINT coach_training_cases_profile_check CHECK (char_length(profile_url) BETWEEN 1 AND 2000),
    CONSTRAINT coach_training_cases_note_check CHECK (note IS NULL OR char_length(note) <= 2000)
);

-- One active case per conversation; an archived one may be re-added.
CREATE UNIQUE INDEX coach_training_cases_thread_key
    ON public.coach_training_cases (instance_id, profile_url) WHERE archived_at IS NULL;

CREATE TABLE public.coach_training_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    case_id bigint NOT NULL,
    version_id bigint NOT NULL,
    cut_after_message_id bigint,
    thread_marker text NOT NULL,
    output jsonb,
    model text,
    error text,
    created_by uuid NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT coach_training_runs_pkey PRIMARY KEY (id),
    CONSTRAINT coach_training_runs_case_fkey FOREIGN KEY (case_id)
        REFERENCES public.coach_training_cases(id) ON DELETE CASCADE,
    CONSTRAINT coach_training_runs_version_fkey FOREIGN KEY (version_id)
        REFERENCES public.coach_prompt_versions(id),
    CONSTRAINT coach_training_runs_created_by_fkey FOREIGN KEY (created_by)
        REFERENCES public.users(id),
    CONSTRAINT coach_training_runs_marker_check CHECK (char_length(thread_marker) BETWEEN 1 AND 400),
    CONSTRAINT coach_training_runs_result_check CHECK (
        (output IS NOT NULL AND jsonb_typeof(output) = 'object' AND error IS NULL)
        OR (output IS NULL AND error IS NOT NULL AND char_length(error) <= 2000))
);

CREATE INDEX coach_training_runs_case_idx
    ON public.coach_training_runs (case_id, version_id, created_at DESC);

CREATE TABLE public.coach_training_feedback (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    run_id bigint NOT NULL,
    case_id bigint NOT NULL,
    version_id bigint NOT NULL,
    target text NOT NULL,
    target_index integer,
    verdict text,
    comment text,
    consumed_by_version_id bigint,
    created_by uuid NOT NULL,
    created_by_name text NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT coach_training_feedback_pkey PRIMARY KEY (id),
    CONSTRAINT coach_training_feedback_run_fkey FOREIGN KEY (run_id)
        REFERENCES public.coach_training_runs(id) ON DELETE CASCADE,
    CONSTRAINT coach_training_feedback_case_fkey FOREIGN KEY (case_id)
        REFERENCES public.coach_training_cases(id) ON DELETE CASCADE,
    CONSTRAINT coach_training_feedback_version_fkey FOREIGN KEY (version_id)
        REFERENCES public.coach_prompt_versions(id),
    CONSTRAINT coach_training_feedback_consumed_fkey FOREIGN KEY (consumed_by_version_id)
        REFERENCES public.coach_prompt_versions(id),
    CONSTRAINT coach_training_feedback_created_by_fkey FOREIGN KEY (created_by)
        REFERENCES public.users(id),
    CONSTRAINT coach_training_feedback_target_check CHECK (
        (target = 'take' AND target_index IS NULL)
        OR (target IN ('idea', 'issue') AND target_index BETWEEN 0 AND 49)),
    CONSTRAINT coach_training_feedback_verdict_check CHECK (verdict IS NULL OR verdict IN ('good', 'bad')),
    CONSTRAINT coach_training_feedback_comment_check CHECK (comment IS NULL OR char_length(comment) <= 4000),
    CONSTRAINT coach_training_feedback_created_by_name_check
        CHECK (char_length(btrim(created_by_name)) BETWEEN 1 AND 120)
);

-- One feedback row per thing commented on in a run.
CREATE UNIQUE INDEX coach_training_feedback_target_key
    ON public.coach_training_feedback (run_id, target, (coalesce(target_index, -1)));
CREATE INDEX coach_training_feedback_pending_idx
    ON public.coach_training_feedback (case_id) WHERE consumed_by_version_id IS NULL;

ALTER TABLE public.conversation_coaching
    ADD COLUMN prompt_version_id bigint,
    ADD CONSTRAINT conversation_coaching_prompt_version_fkey FOREIGN KEY (prompt_version_id)
        REFERENCES public.coach_prompt_versions(id);

CREATE TRIGGER touch_coach_training_cases_updated_at BEFORE UPDATE ON public.coach_training_cases
    FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();
CREATE TRIGGER touch_coach_training_feedback_updated_at BEFORE UPDATE ON public.coach_training_feedback
    FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();
CREATE TRIGGER touch_coach_prompt_state_updated_at BEFORE UPDATE ON public.coach_prompt_state
    FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

ALTER TABLE public.coach_prompt_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coach_prompt_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coach_training_cases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coach_training_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.coach_training_feedback ENABLE ROW LEVEL SECURITY;

